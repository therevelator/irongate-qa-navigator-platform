/**
 * Writes demo datasets as idempotent SQL files (INSERT … ON CONFLICT DO NOTHING; rows for
 * existing teams inside DO blocks that re-check at apply time that the team still lacks the
 * data), split into numbered parts of at most ~1.4 MB.
 */
import fs from 'fs';
import path from 'path';
import { buildDemoDataset, renderScript, CLEAR_STATEMENTS, todayUtc, DEMO_COMPANY_NAME, Dataset } from './demoData';

const MAX_FILE_BYTES = 1_400_000;
export type SqlKind = 'seed' | 'fill' | 'clear';

const DESCRIPTION: Record<SqlKind, string[]> = {
  seed: [`-- Demo company: ${DEMO_COMPANY_NAME}.`,
    '-- Idempotent: every INSERT is ON CONFLICT DO NOTHING; apply the parts in order. Existing (non-demo) rows are never changed.'],
  fill: ['-- Fills active teams of existing companies that lack data, with demo- ids (removed by the clear script).',
    '-- Each block re-checks that the team exists and still has no real rows of that kind. Existing rows are never changed.'],
  clear: ['-- Deletes only demo rows: ids starting with "demo-", rows of the demo company, and snapshot ids >= 1000000000.'],
};

/** Numbered part paths: demo-seed.sql -> demo-seed-01.sql, demo-seed-02.sql, ... */
function partPath(file: string, i: number, total: number): string {
  if (total === 1) return file;
  const ext = path.extname(file) || '.sql';
  const base = file.slice(0, file.length - path.extname(file).length);
  return `${base}-${String(i).padStart(2, '0')}${ext}`;
}

export function writeSqlFiles(file: string, statements: string[], kind: SqlKind, today: string): string[] {
  const chunks: string[][] = [[]];
  let size = 0;
  for (const sql of statements) {
    const bytes = Buffer.byteLength(sql, 'utf8') + 2;
    if (size + bytes > MAX_FILE_BYTES && chunks[chunks.length - 1].length) {
      chunks.push([]);
      size = 0;
    }
    chunks[chunks.length - 1].push(sql);
    size += bytes;
  }
  fs.mkdirSync(path.dirname(path.resolve(file)), { recursive: true });
  return chunks.map((chunk, i) => {
    const p = partPath(file, i + 1, chunks.length);
    const header = [
      `-- QE Navigator: demo (sample) data, ${kind} — part ${i + 1} of ${chunks.length}; history ends ${today}.`,
      ...DESCRIPTION[kind], '-- Generated by npm run seed:demo (see README, "Sample (demo) data").', '', 'BEGIN;', '',
    ].join('\n');
    fs.writeFileSync(p, `${header}${chunk.join('\n\n')}\n\nCOMMIT;\n`);
    return p;
  });
}

export function writeDatasetSql(file: string, ds: Dataset, kind: 'seed' | 'fill'): string[] {
  return writeSqlFiles(file, renderScript(ds).map(s => s.sql), kind, ds.today);
}

export function writeDemoSqlFiles(file: string, opts: { today?: string; clear?: boolean } = {}): string[] {
  const today = opts.today ?? todayUtc();
  if (opts.clear) return writeSqlFiles(file, CLEAR_STATEMENTS.map(s => `${s.sql};`), 'clear', today);
  return writeDatasetSql(file, buildDemoDataset({ today }), 'seed');
}
