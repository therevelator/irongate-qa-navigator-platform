/**
 * Writes the demo dataset as idempotent SQL files (INSERT … ON CONFLICT DO NOTHING),
 * split into numbered parts of at most ~1.4 MB. No database connection is made.
 */
import fs from 'fs';
import path from 'path';
import { buildDemoDataset, renderStatements, CLEAR_STATEMENTS, demoSummary, todayUtc, DEMO_COMPANY_NAME } from './demoData';

const MAX_FILE_BYTES = 1_400_000;

function header(part: number, parts: number, today: string, kind: 'seed' | 'clear'): string {
  return [
    `-- IronGate QA Navigator: demo (sample) data ${kind === 'seed' ? 'seed' : 'removal'} — part ${part} of ${parts}`,
    `-- Company: ${DEMO_COMPANY_NAME}; history ends ${today}. Generated by: npm run seed:demo -- --sql <file>`,
    kind === 'seed'
      ? '-- Idempotent: every INSERT is ON CONFLICT DO NOTHING; apply the parts in order. Existing (non-demo) rows are never changed.'
      : '-- Deletes only rows of the demo company (ids / company / team / user ids starting with "demo-").',
    '',
    'BEGIN;',
    '',
  ].join('\n');
}

/** Numbered part paths: demo-seed.sql -> demo-seed-01.sql, demo-seed-02.sql, ... */
function partPath(file: string, i: number, total: number): string {
  if (total === 1) return file;
  const ext = path.extname(file) || '.sql';
  const base = file.slice(0, file.length - path.extname(file).length);
  return `${base}-${String(i).padStart(2, '0')}${ext}`;
}

export function writeDemoSqlFiles(file: string, opts: { today?: string; clear?: boolean } = {}): string[] {
  const today = opts.today ?? todayUtc();
  const statements = opts.clear
    ? CLEAR_STATEMENTS.map(s => `${s.sql};`)
    : renderStatements(buildDemoDataset({ today })).map(s => s.sql);

  const chunks: string[][] = [[]];
  let size = 0;
  for (const sql of statements) {
    const bytes = Buffer.byteLength(sql, 'utf8') + 2;
    if (size + bytes > MAX_FILE_BYTES && chunks[chunks.length - 1].length) {
      chunks.push([]);
      size = 0;
    }
    chunks[chunks.length - 1].push(sql);
    size += bytes;
  }

  fs.mkdirSync(path.dirname(path.resolve(file)), { recursive: true });
  const written: string[] = [];
  chunks.forEach((chunk, i) => {
    const p = partPath(file, i + 1, chunks.length);
    fs.writeFileSync(p, `${header(i + 1, chunks.length, today, opts.clear ? 'clear' : 'seed')}${chunk.join('\n\n')}\n\nCOMMIT;\n`);
    written.push(p);
  });
  return written;
}

export { demoSummary };
