/**
 * One-off converter: MySQL (irongate_qa) -> PostgreSQL / Supabase.
 *
 * Reads the schema and data from a running MySQL database (e.g. one restored from
 * db_snapshots/latest_snapshot.sql) and writes:
 *   - supabase/migrations/<ts>_initial_schema.sql   (tables, constraints, indexes, triggers, RLS)
 *   - db_snapshots/latest_snapshot.postgres.sql     (data, as INSERT statements)
 *
 * Usage:
 *   MYSQL_URL=mysql://user:pass@127.0.0.1:3306/irongate_qa npx tsx scripts/mysql-to-postgres.ts
 *
 * See docs/SUPABASE_MIGRATION.md for the full procedure.
 */
import mysql from 'mysql2/promise';
import fs from 'fs';
import path from 'path';

const SCHEMA_OUT = process.env.SCHEMA_OUT || 'supabase/migrations/20261020000000_initial_schema.sql';
const DATA_OUT = process.env.DATA_OUT || 'db_snapshots/latest_snapshot.postgres.sql';
const BATCH = 500;

interface Column {
  TABLE_NAME: string;
  COLUMN_NAME: string;
  ORDINAL_POSITION: number;
  COLUMN_DEFAULT: string | null;
  IS_NULLABLE: 'YES' | 'NO';
  DATA_TYPE: string;
  COLUMN_TYPE: string;
  EXTRA: string;
}

const q = (id: string) => `"${id}"`;
const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;

// Postgres identifiers are limited to 63 bytes
function objName(...parts: string[]): string {
  const name = parts.join('_');
  return name.length <= 63 ? name : name.slice(0, 63);
}

function isBool(c: Column) {
  return c.COLUMN_TYPE === 'tinyint(1)';
}

function pgType(c: Column): string {
  const t = c.COLUMN_TYPE.toLowerCase();
  if (isBool(c)) return 'boolean';
  if (c.EXTRA.includes('auto_increment')) {
    return (t.startsWith('bigint') ? 'bigint' : 'integer') + ' GENERATED BY DEFAULT AS IDENTITY';
  }
  switch (c.DATA_TYPE) {
    case 'tinyint':
    case 'smallint':
      return 'smallint';
    case 'mediumint':
    case 'int':
      return t.includes('unsigned') ? 'bigint' : 'integer';
    case 'bigint':
      return 'bigint';
    case 'decimal':
      return t.replace('decimal', 'numeric').replace(' unsigned', '');
    case 'float':
      return 'real';
    case 'double':
      return 'double precision';
    // char(n) pads with spaces in Postgres; varchar keeps ids exactly as stored
    case 'char':
    case 'varchar':
      return t.replace(/^char/, 'varchar');
    case 'tinytext':
    case 'text':
    case 'mediumtext':
    case 'longtext':
      return 'text';
    case 'enum':
      return 'text';
    case 'json':
      return 'jsonb';
    case 'date':
      return 'date';
    case 'datetime':
    case 'timestamp':
      return 'timestamptz';
    case 'time':
      return 'time';
    case 'blob':
    case 'longblob':
    case 'varbinary':
    case 'binary':
      return 'bytea';
    default:
      throw new Error(`Unmapped MySQL type ${c.COLUMN_TYPE} on ${c.TABLE_NAME}.${c.COLUMN_NAME}`);
  }
}

function pgDefault(c: Column): string | null {
  const d = c.COLUMN_DEFAULT;
  if (d === null || d === 'NULL') return null;
  if (c.EXTRA.includes('DEFAULT_GENERATED')) {
    if (/^current_timestamp/i.test(d)) return 'now()';
    if (d === 'uuid()') return 'gen_random_uuid()::text';
    if (d.startsWith('concat(') && d.includes('dm-')) {
      return `('dm-' || floor(extract(epoch from now()))::bigint || '-' || substr(gen_random_uuid()::text, 1, 8))`;
    }
    throw new Error(`Unmapped default expression ${d} on ${c.TABLE_NAME}.${c.COLUMN_NAME}`);
  }
  if (isBool(c)) return d === '0' ? 'false' : 'true';
  if (['int', 'smallint', 'tinyint', 'bigint', 'decimal', 'float', 'double'].includes(c.DATA_TYPE)) return d;
  return lit(d);
}

function enumValues(columnType: string): string[] {
  return [...columnType.matchAll(/'((?:[^']|'')*)'/g)].map(m => m[1].replace(/''/g, "'"));
}

async function main() {
  const url = process.env.MYSQL_URL;
  if (!url) throw new Error('MYSQL_URL is required');
  const conn = await mysql.createConnection({ uri: url, dateStrings: true, timezone: 'Z', supportBigNumbers: true, bigNumberStrings: true });
  await conn.query("SET time_zone = '+00:00'");
  const [[{ db }]] = (await conn.query('SELECT DATABASE() AS db')) as any;

  const [tablesRows] = (await conn.query(
    `SELECT TABLE_NAME FROM information_schema.TABLES WHERE TABLE_SCHEMA = ? AND TABLE_TYPE = 'BASE TABLE' ORDER BY TABLE_NAME`, [db]
  )) as any;
  const tables: string[] = tablesRows.map((r: any) => r.TABLE_NAME);

  const [colRows] = (await conn.query(
    `SELECT TABLE_NAME, COLUMN_NAME, ORDINAL_POSITION, COLUMN_DEFAULT, IS_NULLABLE, DATA_TYPE, COLUMN_TYPE, EXTRA
     FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = ? ORDER BY TABLE_NAME, ORDINAL_POSITION`, [db]
  )) as any;
  const columns = new Map<string, Column[]>();
  for (const c of colRows as Column[]) {
    if (!columns.has(c.TABLE_NAME)) columns.set(c.TABLE_NAME, []);
    columns.get(c.TABLE_NAME)!.push(c);
  }

  const [statRows] = (await conn.query(
    `SELECT TABLE_NAME, INDEX_NAME, NON_UNIQUE, SEQ_IN_INDEX, COLUMN_NAME
     FROM information_schema.STATISTICS WHERE TABLE_SCHEMA = ? ORDER BY TABLE_NAME, INDEX_NAME, SEQ_IN_INDEX`, [db]
  )) as any;
  const indexes = new Map<string, Map<string, { unique: boolean; cols: string[] }>>();
  for (const s of statRows) {
    if (!indexes.has(s.TABLE_NAME)) indexes.set(s.TABLE_NAME, new Map());
    const t = indexes.get(s.TABLE_NAME)!;
    if (!t.has(s.INDEX_NAME)) t.set(s.INDEX_NAME, { unique: Number(s.NON_UNIQUE) === 0, cols: [] });
    t.get(s.INDEX_NAME)!.cols.push(s.COLUMN_NAME);
  }

  const [fkRows] = (await conn.query(
    `SELECT k.TABLE_NAME, k.CONSTRAINT_NAME, k.COLUMN_NAME, k.REFERENCED_TABLE_NAME, k.REFERENCED_COLUMN_NAME,
            r.UPDATE_RULE, r.DELETE_RULE
     FROM information_schema.KEY_COLUMN_USAGE k
     JOIN information_schema.REFERENTIAL_CONSTRAINTS r
       ON r.CONSTRAINT_SCHEMA = k.CONSTRAINT_SCHEMA AND r.CONSTRAINT_NAME = k.CONSTRAINT_NAME AND r.TABLE_NAME = k.TABLE_NAME
     WHERE k.TABLE_SCHEMA = ? AND k.REFERENCED_TABLE_NAME IS NOT NULL
     ORDER BY k.TABLE_NAME, k.CONSTRAINT_NAME, k.ORDINAL_POSITION`, [db]
  )) as any;
  const fks = new Map<string, { table: string; cols: string[]; refTable: string; refCols: string[]; onUpdate: string; onDelete: string }>();
  for (const f of fkRows) {
    const key = `${f.TABLE_NAME}.${f.CONSTRAINT_NAME}`;
    if (!fks.has(key)) {
      fks.set(key, { table: f.TABLE_NAME, cols: [], refTable: f.REFERENCED_TABLE_NAME, refCols: [], onUpdate: f.UPDATE_RULE, onDelete: f.DELETE_RULE });
    }
    fks.get(key)!.cols.push(f.COLUMN_NAME);
    fks.get(key)!.refCols.push(f.REFERENCED_COLUMN_NAME);
  }

  // ---------------------------------------------------------------- schema
  const out: string[] = [];
  out.push(`-- IronGate QA Navigator: initial PostgreSQL schema (converted from MySQL by scripts/mysql-to-postgres.ts)`);
  out.push(`-- Apply with: psql "$DATABASE_URL" -f ${SCHEMA_OUT}\n`);
  out.push(`CREATE EXTENSION IF NOT EXISTS pgcrypto;\n`);
  out.push(`-- Replaces MySQL's "ON UPDATE CURRENT_TIMESTAMP"`);
  out.push(`CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;\n`);

  const triggers: string[] = [];
  const identityCols: { table: string; col: string }[] = [];

  for (const t of tables) {
    const cols = columns.get(t)!;
    const lines: string[] = [];
    for (const c of cols) {
      let line = `  ${q(c.COLUMN_NAME)} ${pgType(c)}`;
      const def = c.EXTRA.includes('auto_increment') ? null : pgDefault(c);
      if (def !== null) line += ` DEFAULT ${def}`;
      if (c.IS_NULLABLE === 'NO') line += ' NOT NULL';
      if (c.DATA_TYPE === 'enum') {
        line += ` CHECK (${q(c.COLUMN_NAME)} IN (${enumValues(c.COLUMN_TYPE).map(lit).join(', ')}))`;
      }
      lines.push(line);
      if (c.EXTRA.includes('auto_increment')) identityCols.push({ table: t, col: c.COLUMN_NAME });
      if (c.EXTRA.toLowerCase().includes('on update current_timestamp')) {
        if (c.COLUMN_NAME !== 'updated_at') throw new Error(`ON UPDATE column ${t}.${c.COLUMN_NAME} is not updated_at`);
        triggers.push(`CREATE TRIGGER ${q(objName(t, 'set_updated_at'))} BEFORE UPDATE ON ${q(t)} FOR EACH ROW EXECUTE FUNCTION set_updated_at();`);
      }
    }
    const idx = indexes.get(t) || new Map();
    const pk = idx.get('PRIMARY');
    if (pk) lines.push(`  CONSTRAINT ${q(objName(t, 'pkey'))} PRIMARY KEY (${pk.cols.map(q).join(', ')})`);
    for (const [name, i] of idx) {
      if (name === 'PRIMARY' || !i.unique) continue;
      lines.push(`  CONSTRAINT ${q(objName(t, name))} UNIQUE (${i.cols.map(q).join(', ')})`);
    }
    out.push(`CREATE TABLE ${q(t)} (\n${lines.join(',\n')}\n);\n`);
  }

  out.push(`-- Secondary indexes`);
  for (const t of tables) {
    const idx = indexes.get(t) || new Map();
    for (const [name, i] of idx) {
      if (name === 'PRIMARY' || i.unique) continue;
      out.push(`CREATE INDEX ${q(objName(t, name))} ON ${q(t)} (${i.cols.map(q).join(', ')});`);
    }
  }
  out.push('');

  out.push(`-- MySQL compared emails case-insensitively (utf8mb4_unicode_ci); keep that guarantee`);
  out.push(`CREATE UNIQUE INDEX "users_email_lower_key" ON "users" (lower("email"));\n`);

  out.push(`-- Foreign keys`);
  for (const [key, f] of fks) {
    const name = key.split('.')[1];
    out.push(
      `ALTER TABLE ${q(f.table)} ADD CONSTRAINT ${q(objName(f.table, name))} FOREIGN KEY (${f.cols.map(q).join(', ')}) ` +
      `REFERENCES ${q(f.refTable)} (${f.refCols.map(q).join(', ')}) ON UPDATE ${f.onUpdate} ON DELETE ${f.onDelete};`
    );
  }
  out.push('');

  out.push(`-- updated_at triggers`);
  out.push(...triggers, '');

  out.push(`-- The app connects directly as the database owner, never through Supabase's Data API.`);
  out.push(`-- Enabling RLS with no policies keeps these tables (incl. password hashes) unreachable via the anon/authenticated keys.`);
  for (const t of tables) out.push(`ALTER TABLE ${q(t)} ENABLE ROW LEVEL SECURITY;`);
  out.push('');

  fs.mkdirSync(path.dirname(SCHEMA_OUT), { recursive: true });
  fs.writeFileSync(SCHEMA_OUT, out.join('\n'));
  console.log(`Wrote ${SCHEMA_OUT}`);

  // ---------------------------------------------------------------- data
  const data: string[] = [];
  data.push(`-- IronGate QA Navigator data snapshot (converted from MySQL by scripts/mysql-to-postgres.ts)`);
  data.push(`-- Load AFTER the schema migration: psql "$DATABASE_URL" -f ${DATA_OUT}\n`);
  data.push(`BEGIN;`);
  data.push(`-- Skip FK checks and updated_at triggers while loading, like mysqldump's FOREIGN_KEY_CHECKS=0`);
  data.push(`SET LOCAL session_replication_role = replica;\n`);

  let total = 0;
  for (const t of tables) {
    const cols = columns.get(t)!;
    const [rows] = (await conn.query(`SELECT * FROM \`${t}\``)) as any;
    if (!rows.length) continue;
    total += rows.length;
    const colList = cols.map(c => q(c.COLUMN_NAME)).join(', ');
    for (let i = 0; i < rows.length; i += BATCH) {
      const values = rows.slice(i, i + BATCH).map((r: any) =>
        '(' + cols.map(c => {
          const v = r[c.COLUMN_NAME];
          if (v === null || v === undefined) return 'NULL';
          if (isBool(c)) return Number(v) ? 'true' : 'false';
          if (typeof v === 'number') return String(v);
          if (c.DATA_TYPE === 'json') return lit(typeof v === 'string' ? v : JSON.stringify(v));
          if (c.DATA_TYPE === 'timestamp' || c.DATA_TYPE === 'datetime') return lit(`${v}+00`);
          if (Buffer.isBuffer(v)) return `'\\x${v.toString('hex')}'`;
          return lit(String(v));
        }).join(', ') + ')'
      );
      data.push(`INSERT INTO ${q(t)} (${colList}) VALUES\n${values.join(',\n')};\n`);
    }
  }

  data.push(`-- Move identity sequences past the imported ids`);
  for (const { table, col } of identityCols) {
    data.push(`SELECT setval(pg_get_serial_sequence('${q(table)}', '${col}'), COALESCE((SELECT MAX(${q(col)}) FROM ${q(table)}), 0) + 1, false);`);
  }
  data.push(`\nCOMMIT;\n`);

  fs.mkdirSync(path.dirname(DATA_OUT), { recursive: true });
  fs.writeFileSync(DATA_OUT, data.join('\n'));
  console.log(`Wrote ${DATA_OUT} (${total} rows from ${tables.length} tables)`);

  await conn.end();
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
