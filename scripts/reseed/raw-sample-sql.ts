/**
 * Standalone SQL that adds the v2 phase-1 sample raw CI data (test runs with per-test results,
 * coverage reports with per-file coverage, pipeline runs with stages, flaky-test evidence; the last
 * 14 days, following each team's story) to teams of an existing company WITHOUT wiping anything:
 * every statement skips rows that exist (re-running adds only the missing days), and a team with
 * real raw CI data gets none. For a SQL console or the Supabase Management API (plain SQL text).
 *
 * The calculated metrics behind "How this was calculated" (metric_evidence) are filled by the
 * nightly calc-recompute job (or Netlify → Functions → calc-recompute → Run now); the evidence
 * views (flaky tests, lowest-coverage files, slowest tests, failing stages) work at once.
 *
 * Usage: npx tsx scripts/reseed/raw-sample-sql.ts --company mft-meridian \
 *          --stories scripts/reseed/stories.json --names "Payments Core,Lending Journey,Mobile Experience" --out <dir>
 *   writes <dir>/raw-sample-<company>.sql and <dir>/raw-sample-<company>-remove.sql
 */
import fs from 'node:fs';
import path from 'node:path';
import { rawSampleSqlForTeam, RAW_SAMPLE_DAYS, RAW_SAMPLE_PREFIX } from '../../server/seeds/demoRaw';
import { sampleHealthSeries } from '../../server/seeds/demoData';

const arg = (n: string) => { const i = process.argv.indexOf(n); return i >= 0 ? process.argv[i + 1] : undefined; };
const company = arg('--company');
const storiesFile = arg('--stories');
const out = arg('--out');
if (!company || !storiesFile || !out) { console.error('--company, --stories and --out are required'); process.exit(2); }
const stories: Record<string, Array<[number, number]>> = JSON.parse(fs.readFileSync(storiesFile, 'utf8'));
const ids = Object.keys(stories);
const names = (arg('--names') ?? '').split(',').map((s) => s.trim());
const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;

const parts: string[] = [
  `-- QE Navigator v2 phase 1: sample raw CI data for ${company} (${ids.join(', ')}).`,
  `-- Adds only; skips what exists; never touches other rows. Generated by scripts/reseed/raw-sample-sql.ts.`,
  `-- Needs migration 20261129000000_raw_ingestion_phase1.sql applied first.`,
  `DO $$ BEGIN
  IF (SELECT COUNT(*) FROM teams WHERE company_id = ${lit(company)} AND id IN (${ids.map(lit).join(', ')})) <> ${ids.length} THEN
    RAISE EXCEPTION 'Not every team of ${company} was found: ${ids.join(', ')}';
  END IF;
  IF to_regclass('public.test_runs') IS NULL THEN RAISE EXCEPTION 'Apply migration 20261129000000_raw_ingestion_phase1.sql first'; END IF;
END $$;`,
];
ids.forEach((id, i) => {
  const name = names[i] || id.replace(/^mft-team-/, '').replace(/-\d+$/, '').replace(/-/g, ' ');
  parts.push(`-- ${name} (${id})`);
  for (const st of rawSampleSqlForTeam({ id, companyId: company, name, health: sampleHealthSeries({ id, name, platform: null }, RAW_SAMPLE_DAYS, stories) })) parts.push(`${st};`);
});
fs.mkdirSync(out, { recursive: true });
const file = path.join(out, `raw-sample-${company}.sql`);
fs.writeFileSync(file, parts.join('\n\n') + '\n');
const teamList = ids.map(lit).join(', ');
const remove = [
  `-- Remove the sample raw CI data of ${company} added by raw-sample-${company}.sql (sample rows only).`,
  `DELETE FROM flaky_test_evidence WHERE team_id IN (${teamList}) AND EXISTS (SELECT 1 FROM test_runs tr WHERE tr.id = ANY(failed_run_ids) AND tr.is_sample);`,
  `DELETE FROM metric_evidence WHERE team_id IN (${teamList}) AND NOT EXISTS (SELECT 1 FROM test_runs tr WHERE tr.team_id = metric_evidence.team_id AND NOT tr.is_sample);`,
  `DELETE FROM pipeline_runs_raw WHERE team_id IN (${teamList}) AND id LIKE '${RAW_SAMPLE_PREFIX}%';`,
  `DELETE FROM coverage_reports WHERE team_id IN (${teamList}) AND id LIKE '${RAW_SAMPLE_PREFIX}%';`,
  `DELETE FROM test_runs WHERE team_id IN (${teamList}) AND id LIKE '${RAW_SAMPLE_PREFIX}%';`,
];
fs.writeFileSync(path.join(out, `raw-sample-${company}-remove.sql`), remove.join('\n') + '\n');
console.log(`${file}: ${fs.statSync(file).size} bytes`);
