/**
 * Standalone SQL that adds the v2 phase-1 sample raw CI data (test runs with per-test results,
 * coverage reports with per-file coverage, pipeline runs with stages, flaky-test evidence; the last
 * 14 days, following each team's story) to teams of an existing company WITHOUT wiping anything:
 * every statement skips rows that exist (re-running adds only the missing days), and a team with
 * real raw CI data gets none. For a SQL console or the Supabase Management API (plain SQL text).
 *
 * The calculated metrics behind "How this was calculated" (metric_evidence) are filled by the
 * nightly sample refresh (demo-refresh; it also adds each new day) or the operator panel's "Refresh
 * sample data now"; the evidence views (flaky tests, lowest-coverage files, slowest tests, failing
 * stages) work at once.
 *
 * Usage: npx tsx scripts/reseed/raw-sample-sql.ts --company mft-meridian \
 *          --stories scripts/reseed/stories.json --names "Payments Core,Lending Journey,Mobile Experience" --out <dir>
 *   writes <dir>/raw-sample-<company>.sql and <dir>/raw-sample-<company>-remove.sql
 *
 * --delivery-only: only the phase-2 sample (deployments with their commits, incidents with their
 * status updates; the last 35 days), for a company that already has the phase-1 sample:
 *   writes <dir>/delivery-sample-<company>.sql and <dir>/delivery-sample-<company>-remove.sql
 *
 * --work-only: only the phase-3 sample (a year of issues with sprints, bugs and status changes, and weekly
 * SARIF reports with findings), derived in the database from each team's own KPI history and sprints
 * (server/seeds/demoWork.ts), for a company that already has the phase-1 sample (its coverage size):
 *   writes <dir>/work-sample-<company>.sql and <dir>/work-sample-<company>-remove.sql
 */
import fs from 'node:fs';
import path from 'node:path';
import { deliverySampleSqlForTeam, rawSampleSqlForTeam, RAW_SAMPLE_PREFIX, SAMPLE_HEALTH_DAYS } from '../../server/seeds/demoRaw';
import { sampleHealthSeries } from '../../server/seeds/demoData';
import { workSampleSqlForTeam } from '../../server/seeds/demoWork';

const arg = (n: string) => { const i = process.argv.indexOf(n); return i >= 0 ? process.argv[i + 1] : undefined; };
const company = arg('--company');
const storiesFile = arg('--stories');
const out = arg('--out');
if (!company || !storiesFile || !out) { console.error('--company, --stories and --out are required'); process.exit(2); }
const stories: Record<string, Array<[number, number]>> = JSON.parse(fs.readFileSync(storiesFile, 'utf8'));
const ids = Object.keys(stories);
const names = (arg('--names') ?? '').split(',').map((s) => s.trim());
const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;
const deliveryOnly = process.argv.includes('--delivery-only');
const workOnly = process.argv.includes('--work-only');
const base = workOnly ? 'work-sample' : deliveryOnly ? 'delivery-sample' : 'raw-sample';

const parts: string[] = workOnly ? [
  `-- QE Navigator v2 phase 3: sample issues (sprints, stories, bugs, status changes) and weekly SARIF reports for ${company} (${ids.join(', ')}), the last year.`,
  `-- Derived in the database from each team's KPI history (kpi_snapshots) and sprints (sprint_velocity), so the calculated values match the KPIs.`,
  `-- Adds only; skips what exists; never touches other rows; a team with real issues or reports gets none. Generated by scripts/reseed/raw-sample-sql.ts --work-only.`,
  `-- Needs migration 20261201000000_raw_ingestion_phase3_work_quality.sql applied first.`,
  `DO $$ BEGIN
  IF (SELECT COUNT(*) FROM teams WHERE company_id = ${lit(company)} AND id IN (${ids.map(lit).join(', ')})) <> ${ids.length} THEN
    RAISE EXCEPTION 'Not every team of ${company} was found: ${ids.join(', ')}';
  END IF;
  IF to_regclass('public.issues') IS NULL OR to_regclass('public.analysis_reports') IS NULL THEN RAISE EXCEPTION 'Apply migration 20261201000000_raw_ingestion_phase3_work_quality.sql first'; END IF;
END $$;`,
] : [
  deliveryOnly
    ? `-- QE Navigator v2 phase 2: sample deployments, commits and incidents for ${company} (${ids.join(', ')}), the last 35 days.`
    : `-- QE Navigator v2 phase 1 and 2: sample raw CI data, deployments and incidents for ${company} (${ids.join(', ')}).`,
  `-- Adds only; skips what exists; never touches other rows. Generated by scripts/reseed/raw-sample-sql.ts.`,
  `-- Needs migration 20261129000000_raw_ingestion_phase1.sql${deliveryOnly ? ' and 20261130000000_raw_ingestion_phase2_delivery.sql' : ' and 20261130000000_raw_ingestion_phase2_delivery.sql'} applied first.`,
  `DO $$ BEGIN
  IF (SELECT COUNT(*) FROM teams WHERE company_id = ${lit(company)} AND id IN (${ids.map(lit).join(', ')})) <> ${ids.length} THEN
    RAISE EXCEPTION 'Not every team of ${company} was found: ${ids.join(', ')}';
  END IF;
  IF to_regclass('public.test_runs') IS NULL THEN RAISE EXCEPTION 'Apply migration 20261129000000_raw_ingestion_phase1.sql first'; END IF;
  IF to_regclass('public.deployments_raw') IS NULL THEN RAISE EXCEPTION 'Apply migration 20261130000000_raw_ingestion_phase2_delivery.sql first'; END IF;
END $$;`,
];
ids.forEach((id, i) => {
  const name = names[i] || id.replace(/^mft-team-/, '').replace(/-\d+$/, '').replace(/-/g, ' ');
  parts.push(`-- ${name} (${id})`);
  const team = { id, companyId: company, name, health: sampleHealthSeries({ id, name, platform: null }, SAMPLE_HEALTH_DAYS, stories) };
  const statements = workOnly ? workSampleSqlForTeam(team) : deliveryOnly ? deliverySampleSqlForTeam(team) : rawSampleSqlForTeam(team);
  for (const st of statements) parts.push(`${st};`);
});
fs.mkdirSync(out, { recursive: true });
const file = path.join(out, `${base}-${company}.sql`);
fs.writeFileSync(file, parts.join('\n\n') + '\n');
const teamList = ids.map(lit).join(', ');
const removeDelivery = [
  `DELETE FROM metric_evidence WHERE team_id IN (${teamList}) AND metric_key IN ('deployment_frequency', 'lead_time', 'change_failure_rate', 'mttr', 'mtbf', 'availability', 'incidents_per_deploy', 'infrastructure_failures')
     AND NOT EXISTS (SELECT 1 FROM deployments_raw d WHERE d.team_id = metric_evidence.team_id AND NOT d.is_sample) AND NOT EXISTS (SELECT 1 FROM incidents_raw i WHERE i.team_id = metric_evidence.team_id AND NOT i.is_sample);`,
  `DELETE FROM incidents_raw WHERE team_id IN (${teamList}) AND id LIKE '${RAW_SAMPLE_PREFIX}%';`,
  `DELETE FROM deployment_commits WHERE team_id IN (${teamList}) AND id LIKE '${RAW_SAMPLE_PREFIX}%';`,
  `DELETE FROM deployments_raw WHERE team_id IN (${teamList}) AND id LIKE '${RAW_SAMPLE_PREFIX}%';`,
];
const removeWork = [
  `-- Remove the sample issues and static-analysis reports of ${company} added by work-sample-${company}.sql (sample rows only; changes and findings go with them).`,
  `DELETE FROM metric_evidence WHERE team_id IN (${teamList}) AND metric_key IN ('escape_rate', 'defect_density', 'velocity', 'commitment', 'carryover', 'blocked_time', 'sizing_accuracy')
     AND NOT EXISTS (SELECT 1 FROM issues i WHERE i.team_id = metric_evidence.team_id AND NOT i.is_sample);`,
  `DELETE FROM metric_evidence WHERE team_id IN (${teamList}) AND metric_key IN ('code_quality', 'findings', 'new_findings', 'fixed_findings')
     AND NOT EXISTS (SELECT 1 FROM analysis_reports r WHERE r.team_id = metric_evidence.team_id AND NOT r.is_sample);`,
  `DELETE FROM analysis_reports WHERE team_id IN (${teamList}) AND id LIKE '${RAW_SAMPLE_PREFIX}%';`,
  `DELETE FROM issues WHERE team_id IN (${teamList}) AND id LIKE '${RAW_SAMPLE_PREFIX}%';`,
  `DELETE FROM issue_sprints WHERE team_id IN (${teamList}) AND id LIKE '${RAW_SAMPLE_PREFIX}%';`,
];
const remove = workOnly ? removeWork : deliveryOnly ? [
  `-- Remove the sample deployments, commits and incidents of ${company} added by ${base}-${company}.sql (sample rows only; incident updates go with their incidents).`,
  ...removeDelivery,
] : [
  `-- Remove the sample raw CI data, deployments and incidents of ${company} added by raw-sample-${company}.sql (sample rows only).`,
  ...removeDelivery,
  `DELETE FROM flaky_test_evidence WHERE team_id IN (${teamList}) AND EXISTS (SELECT 1 FROM test_runs tr WHERE tr.id = ANY(failed_run_ids) AND tr.is_sample);`,
  `DELETE FROM metric_evidence WHERE team_id IN (${teamList}) AND NOT EXISTS (SELECT 1 FROM test_runs tr WHERE tr.team_id = metric_evidence.team_id AND NOT tr.is_sample);`,
  `DELETE FROM pipeline_runs_raw WHERE team_id IN (${teamList}) AND id LIKE '${RAW_SAMPLE_PREFIX}%';`,
  `DELETE FROM coverage_reports WHERE team_id IN (${teamList}) AND id LIKE '${RAW_SAMPLE_PREFIX}%';`,
  `DELETE FROM test_runs WHERE team_id IN (${teamList}) AND id LIKE '${RAW_SAMPLE_PREFIX}%';`,
];
fs.writeFileSync(path.join(out, `${base}-${company}-remove.sql`), remove.join('\n') + '\n');
console.log(`${file}: ${fs.statSync(file).size} bytes`);
